for pid, (obs, notes, exprs, issues) in P.items():
    t = json.load(open(f'{W}/workflow/quality/{pid}.template.json'))
    t['observation'] = obs + ' Inspected at 25% (contact sheet), 100% (full panel) and 200% (face crops), and on the composed page.'
    t['views'] = {'thumbnail': True, 'native': True, 'detail': True}
    for k in t['checks']:
        n = notes.get(k) or ('Faces match the sheets at 200%; see faceIdentity.' if k == 'faces' else '')
        t['checks'][k] = {'result': 'pass', 'note': n}
    t['issues'] = issues
    for actor in t['faceIdentity']:
        t['faceIdentity'][actor]['traits'] = T[actor]
        t['faceIdentity'][actor]['expression'] = exprs[actor]
    out = f'{W}/workflow/quality/{pid}.review.json'
    json.dump(t, open(out, 'w'), indent=1, ensure_ascii=False)
    r = subprocess.run(['node', 'cli/workflow.mjs', 'quality-review', pid, out], capture_output=True, text=True)
    print(pid, (r.stdout.strip() or r.stderr.strip().splitlines()[-1] if r.stderr.strip() else '')[-160:])
